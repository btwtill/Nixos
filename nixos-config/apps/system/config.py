"""System app configuration.

Host-specific values (label, watched services, apps) are generated by Nix
into host.json next to this file — edit them in hosts/<host>/configuration.nix
or apps/system/default.nix, not here.
"""
from __future__ import annotations
import json
from pathlib import Path

HOST_CONFIG_PATH = Path(__file__).parent / "host.json"


def _load_host_config() -> dict:
    try:
        return json.loads(HOST_CONFIG_PATH.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        # Running from a checkout (not a Nix build) — use a small fallback.
        return {
            "hostLabel": "dev",
            "apps": ["home-app", "lights-app", "music-app"],
            "services": [{"unit": "sshd.service", "label": "SSH"}],
        }


_host = _load_host_config()

HOST_LABEL: str        = _host.get("hostLabel", "unknown host")
APPS: list[str]        = _host.get("apps", [])
SERVICES: list[dict]   = _host.get("services", [])

